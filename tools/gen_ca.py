#!/usr/bin/env python3
"""Turns a PEM root certificate into the C array the app trusts for its HTTPS request.

    python tools/gen_ca.py isrgrootx1.pem > source/ca_root.h

The certificate is public: https://letsencrypt.org/certs/isrgrootx1.pem
"""
import ssl
import sys

der = ssl.PEM_cert_to_DER_cert(open(sys.argv[1], encoding="ascii").read())

print("/* Generated by tools/gen_ca.py, do not edit. */")
print("#pragma once")
print()
print(f"#define CA_ROOT_SIZE {len(der)}")
print("static const unsigned char CA_ROOT[CA_ROOT_SIZE] = {")
for i in range(0, len(der), 12):
    print("\t" + ", ".join(f"0x{b:02x}" for b in der[i:i + 12]) + ",")
print("};")
